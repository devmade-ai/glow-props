// Requirement: Per-mode individual theme picker + dark/light toggle + burger menu behavior
// Approach: Single IIFE handles individual theme selection (separate light/dark choices),
//   dark/light toggle, and burger menu open/close. Each mode stores its own DaisyUI theme
//   name in localStorage. Toggle flips between modes and applies the stored theme.
// Alternative: Theme combos (curated light/dark pairs) — rejected, users want independent
//   control over their light and dark theme choices without artificial pairing constraints.
// Cleanup contract: every module-level addEventListener is captured in a named handler
//   and registered through trackListener() so window.__theme.dispose() can release it.
//   Pattern: docs/implementations/TIMER_LEAKS.md variant 4 (plain-module singleton).
//   This file is served from public/ as a static script — not in Vite's module graph,
//   no HMR. dispose() exists for tests and future re-init scenarios; the page lifecycle
//   is the normal teardown boundary.

(function () {
  // ===== Defaults =====
  // Requirement: Sensible defaults for first-time visitors
  // Approach: caramellatte (light) and coffee (dark) — warm, welcoming feel.
  //   Users who never touch the picker get a polished default.
  var DEFAULT_LIGHT_THEME = 'caramellatte';
  var DEFAULT_DARK_THEME = 'coffee';

  // Requirement: Random theme on load — theme lists derived from DaisyUI's color-scheme
  // Auto-generated by scripts/generate-meta-colors.mjs — do not edit manually.
  var LIGHT_THEMES = [
    'retro', 'bumblebee', 'fantasy', 'lofi', 'garden', 'pastel', 'cupcake', 'emerald', 
    'light', 'silk', 'nord', 'cyberpunk', 'acid', 'caramellatte', 'corporate', 'autumn', 
    'wireframe', 'valentine', 'cmyk', 'winter', 'lemonade'
  ];
  var DARK_THEMES = [
    'aqua', 'coffee', 'halloween', 'night', 'dark', 'synthwave', 'dim', 'business', 
    'sunset', 'forest', 'dracula', 'abyss', 'luxury', 'black'
  ];

  // ===== PWA status bar meta theme-color =====
  // Requirement: Status bar (time, wifi, battery) color matches the active DaisyUI theme
  // Approach: Light themes use primary hex, dark themes use base-100 hex.
  //   Extracted from DaisyUI's oklch definitions by scripts/generate-meta-colors.mjs.
  // Auto-generated — run `npm run generate:meta-colors` to regenerate after DaisyUI updates.
  var META_COLORS = {
    retro:        '#ff9fa0',
    bumblebee:    '#fdc700',
    fantasy:      '#6d0076',
    lofi:         '#0d0d0d',
    garden:       '#fe0075',
    pastel:       '#e9d4ff',
    cupcake:      '#44ebd3',
    emerald:      '#66cc8a',
    light:        '#422ad5',
    silk:         '#1c1c29',
    nord:         '#5e81ac',
    cyberpunk:    '#ff6596',
    acid:         '#ff00ff',
    caramellatte: '#000000',
    corporate:    '#0082ce',
    autumn:       '#8c0327',
    wireframe:    '#d4d4d4',
    valentine:    '#f43098',
    cmyk:         '#45aeee',
    winter:       '#0069ff',
    lemonade:     '#419400',
    aqua:         '#1a368b',
    coffee:       '#261b25',
    halloween:    '#1b1816',
    night:        '#0f172a',
    dark:         '#1d232a',
    synthwave:    '#09002f',
    dim:          '#2a303c',
    business:     '#202020',
    sunset:       '#121c22',
    forest:       '#1b1717',
    dracula:      '#282a36',
    abyss:        '#001e29',
    luxury:       '#09090b',
    black:        '#000000'
  };

  // ===== Cleanup tracking =====
  // Every module-level addEventListener flows through trackListener so dispose()
  // can release them all. Pattern: TIMER_LEAKS.md variant 4. The 1-element array
  // shape (push a fn that does the removal) handles both window/document/element
  // listeners and matchMedia listeners with one signature.
  var cleanups = [];
  function trackListener(target, type, handler, options) {
    target.addEventListener(type, handler, options);
    cleanups.push(function () { target.removeEventListener(type, handler, options); });
  }

  function getMetaColor(themeName) {
    return META_COLORS[themeName] || '#808080';
  }

  function updateMetaThemeColor(themeName) {
    var color = getMetaColor(themeName);
    document.querySelectorAll('meta[name="theme-color"]').forEach(function (meta) {
      meta.setAttribute('content', color);
    });
  }

  // ===== Storage helpers =====
  function safeStorageSet(key, value) {
    try { localStorage.setItem(key, value); } catch (e) { /* sandboxed */ }
  }

  function safeStorageGet(key) {
    try { return localStorage.getItem(key); } catch (e) { return null; }
  }

  // ===== Theme resolution =====
  // Requirement: Each mode stores its own theme independently
  // Approach: Two localStorage keys — lightTheme and darkTheme.
  //   Falls back to defaults if no stored value or if stored value is invalid.
  //   Validates against known theme lists to prevent unstyled content from
  //   corrupted localStorage.
  function getStoredTheme(dark) {
    var stored = dark ? safeStorageGet('darkTheme') : safeStorageGet('lightTheme');
    var validList = dark ? DARK_THEMES : LIGHT_THEMES;
    var fallback = dark ? DEFAULT_DARK_THEME : DEFAULT_LIGHT_THEME;
    if (stored && validList.indexOf(stored) !== -1) return stored;
    return fallback;
  }

  // ===== Theme application =====
  // Requirement: Both .dark class and data-theme must be set together
  // Why: Tailwind dark: variant reads .dark class on <html>;
  //   DaisyUI component colors read data-theme attribute.
  //   If only one is set, custom dark: utilities and DaisyUI components
  //   fall out of sync — e.g. dark: hover states on light DaisyUI bg.
  function isDark() {
    return document.documentElement.classList.contains('dark');
  }

  // skipPersist: when true, skip writing to localStorage.
  // Used by the cross-tab sync handler — the values already came from
  // another tab's localStorage write, so writing them back is redundant.
  function applyTheme(dark, themeName, skipPersist) {
    // Suppress transitions for the swap (THEME_DARK_MODE.md: theme changes are
    // instant). transition-colors on menu items/buttons is hover feedback and
    // must not animate a whole-page recolor. Two rAFs: the first fires before
    // the paint that applies the new theme, the second after it has painted.
    document.documentElement.classList.add('theme-switching');
    if (dark) {
      document.documentElement.classList.add('dark');
    } else {
      document.documentElement.classList.remove('dark');
    }
    document.documentElement.setAttribute('data-theme', themeName);
    requestAnimationFrame(function () {
      requestAnimationFrame(function () {
        document.documentElement.classList.remove('theme-switching');
      });
    });

    updateMetaThemeColor(themeName);

    if (!skipPersist) {
      safeStorageSet('darkMode', String(dark));
      safeStorageSet(dark ? 'darkTheme' : 'lightTheme', themeName);
    }
    updateThemeLabels(dark);
    updateThemeListVisibility(dark);
    updateThemeIndicators(themeName);
  }

  // ===== UI updates =====
  // Requirement: Show correct toggle label based on current dark/light state.
  //   The aria-label flips with it — the visible span alone leaves the
  //   accessible name stale for screen readers when the label swap happens.
  function updateThemeLabels(dark) {
    var darkLabels = document.querySelectorAll('.theme-label-dark');
    var lightLabels = document.querySelectorAll('.theme-label-light');
    darkLabels.forEach(function (el) {
      if (dark) el.classList.remove('hidden');
      else el.classList.add('hidden');
    });
    lightLabels.forEach(function (el) {
      if (dark) el.classList.add('hidden');
      else el.classList.remove('hidden');
    });
    var toggleBtn = document.getElementById('theme-toggle');
    if (toggleBtn) {
      toggleBtn.setAttribute('aria-label', dark ? 'Switch to light mode' : 'Switch to dark mode');
    }
  }

  // Requirement: Show which theme list matches the current mode
  // Approach: Toggle visibility of .theme-list-light and .theme-list-dark containers.
  //   Only the active mode's themes are visible in the picker.
  function updateThemeListVisibility(dark) {
    var lightLists = document.querySelectorAll('.theme-list-light');
    var darkLists = document.querySelectorAll('.theme-list-dark');
    lightLists.forEach(function (el) {
      if (dark) el.classList.add('hidden');
      else el.classList.remove('hidden');
    });
    darkLists.forEach(function (el) {
      if (dark) el.classList.remove('hidden');
      else el.classList.add('hidden');
    });

    // Update section header to reflect current mode
    var lightHeaders = document.querySelectorAll('.theme-section-label-light');
    var darkHeaders = document.querySelectorAll('.theme-section-label-dark');
    lightHeaders.forEach(function (el) {
      if (dark) el.classList.add('hidden');
      else el.classList.remove('hidden');
    });
    darkHeaders.forEach(function (el) {
      if (dark) el.classList.remove('hidden');
      else el.classList.add('hidden');
    });
  }

  // Requirement: Show which theme is currently active in the picker.
  //   bg-primary/10 + text-primary + font-medium, not bg-base-200 — the buttons
  //   hover with bg-base-200, so the active row was indistinguishable from a
  //   hovered one (BURGER_MENU.md active-theme highlight).
  function updateThemeIndicators(themeName) {
    var items = document.querySelectorAll('[data-theme-pick]');
    items.forEach(function (el) {
      var check = el.querySelector('.theme-check');
      if (el.getAttribute('data-theme-pick') === themeName) {
        if (check) check.classList.remove('invisible');
        el.classList.add('bg-primary/10', 'text-primary', 'font-medium');
      } else {
        if (check) check.classList.add('invisible');
        el.classList.remove('bg-primary/10', 'text-primary', 'font-medium');
      }
    });
  }

  // ===== Initialize =====
  var currentDark = isDark();
  var currentTheme = getStoredTheme(currentDark);
  updateMetaThemeColor(currentTheme);
  updateThemeLabels(currentDark);
  updateThemeListVisibility(currentDark);
  updateThemeIndicators(currentTheme);

  // ===== Dark/Light toggle =====
  // Requirement: Toggle switches mode AND applies the stored theme for the new mode
  var toggle = document.getElementById('theme-toggle');
  function onToggleClick() {
    var newDark = !isDark();
    var theme = getStoredTheme(newDark);
    applyTheme(newDark, theme);
  }
  if (toggle) {
    trackListener(toggle, 'click', onToggleClick);
  }

  // ===== Theme picker =====
  // Requirement: Clicking a theme stores it for the current mode and applies it
  // Approach: Event delegation on [data-theme-pick] buttons — one handler for all themes
  function onThemePickClick(e) {
    var themeBtn = e.target.closest('[data-theme-pick]');
    if (!themeBtn) return;
    var themeName = themeBtn.getAttribute('data-theme-pick');
    if (themeName) {
      applyTheme(isDark(), themeName);
    }
  }
  trackListener(document, 'click', onThemePickClick);

  // ===== Random theme toggle =====
  // Requirement: Toggle that enables random theme selection on each page load
  // Approach: Persists 'randomThemeOnLoad' in localStorage ('true'/'false').
  //   The actual randomization happens in the inline bootstrap script (index.html,
  //   project.html) before first paint, so there's no flash. This handler just
  //   toggles the setting and updates the UI indicator.
  // Alternative: Randomize on toggle click — rejected, the feature is "on load"
  //   so it should only take effect on next page load/refresh.
  var randomToggle = document.getElementById('random-theme-toggle');
  var randomIndicator = document.getElementById('random-theme-indicator');

  function isRandomEnabled() {
    return safeStorageGet('randomThemeOnLoad') === 'true';
  }

  function updateRandomIndicator() {
    if (randomIndicator) {
      var enabled = isRandomEnabled();
      randomIndicator.textContent = enabled ? 'On' : 'Off';
    }
  }

  // Initialize indicator on page load
  updateRandomIndicator();

  function onRandomToggleClick() {
    var newState = !isRandomEnabled();
    safeStorageSet('randomThemeOnLoad', String(newState));
    updateRandomIndicator();
  }
  if (randomToggle) {
    trackListener(randomToggle, 'click', onRandomToggleClick);
  }

  // ===== Cross-tab sync =====
  // storage event only fires in other tabs — values already written by
  // the originating tab, so skipPersist avoids redundant writes
  function onStorageEvent(e) {
    if (e.key === 'darkMode' || e.key === 'lightTheme' || e.key === 'darkTheme') {
      var dark = safeStorageGet('darkMode') === 'true';
      var theme = getStoredTheme(dark);
      applyTheme(dark, theme, true);
    }
    // Sync random toggle indicator across tabs
    if (e.key === 'randomThemeOnLoad') {
      updateRandomIndicator();
    }
  }
  trackListener(window, 'storage', onStorageEvent);

  // Track OS preference changes when user hasn't made an explicit choice
  var mediaQuery = window.matchMedia('(prefers-color-scheme: dark)');
  function onMediaQueryChange(e) {
    if (safeStorageGet('darkMode') === null) {
      var theme = getStoredTheme(e.matches);
      applyTheme(e.matches, theme);
    }
  }
  trackListener(mediaQuery, 'change', onMediaQueryChange);

  // ===== Burger Menu =====
  // Requirement: Disclosure-pattern dropdown with Escape, focus management, click-outside
  // Approach: CSS opacity+scale transitions toggled via class swaps + aria-expanded.
  //   Close on click-outside (document handler), Escape key, and [data-close] item clicks.
  //   Focus first item on open, return focus to trigger on close.
  //   Body scroll locked while open to prevent scroll-through on mobile.
  // Why no backdrop overlay: The navbar's backdrop-filter (backdrop-blur-md) creates a
  //   containing block that traps position:fixed children. A backdrop inside the navbar
  //   only covers the navbar area. Moving it outside would cover the menu too (the menu
  //   is inside the navbar's stacking context at z-30, so an external backdrop at z-40
  //   would sit above it). Document click handler is more robust regardless.
  // Alternative: CSS-only :focus-within — rejected, can't trap Escape or click-outside

  var trigger = document.getElementById('burger-trigger');
  var menu = document.getElementById('burger-menu');

  if (trigger && menu) {
    // Requirement: Smooth open/close transitions for burger menu
    // Approach: CSS opacity+scale transitions, toggled via classes.
    //   pointer-events-none when closed prevents interaction with invisible menu.
    // Alternative: hidden attribute — rejected, no transition possible
    var menuOpen = false;

    function openMenu() {
      menuOpen = true;
      // inert/aria-hidden come off BEFORE the focus move below — an inert
      // element refuses focus. Closed-state markup carries both so the 30+
      // items stay out of the tab order and the accessibility tree.
      menu.removeAttribute('inert');
      menu.removeAttribute('aria-hidden');
      menu.classList.remove('pointer-events-none', 'opacity-0', 'scale-95');
      menu.classList.add('pointer-events-auto', 'opacity-100', 'scale-100');
      trigger.setAttribute('aria-expanded', 'true');
      // Requirement: Prevent body scroll while menu is open
      // Approach: Lock body overflow. Only one component touches this, so
      //   no double-lock conflict (see CLAUDE.md overscroll-contain note).
      // Why not overscroll-contain alone: it only prevents chaining on
      //   scroll containers. Taps on non-scrollable menu areas (nav links,
      //   toggle) still chain to the body without this lock.
      // Requirement: Prevent layout shift when hiding scrollbar
      // Approach: Set scrollbar-gutter to maintain scrollbar space, then hide overflow.
      // Alternative: overflow-y: scroll — rejected, leaves visible scrollbar track.
      document.body.style.scrollbarGutter = 'stable';
      document.body.style.overflow = 'hidden';
      // Focus first menu item after transition starts
      requestAnimationFrame(function () {
        var first = menu.querySelector('a, button');
        if (first) first.focus();
      });
    }

    function closeMenu() {
      menuOpen = false;
      menu.setAttribute('inert', '');
      menu.setAttribute('aria-hidden', 'true');
      menu.classList.remove('pointer-events-auto', 'opacity-100', 'scale-100');
      menu.classList.add('pointer-events-none', 'opacity-0', 'scale-95');
      trigger.setAttribute('aria-expanded', 'false');
      document.body.style.overflow = '';
      document.body.style.scrollbarGutter = '';
      trigger.focus();
    }

    function isOpen() {
      return menuOpen;
    }

    function onTriggerClick() {
      if (isOpen()) closeMenu();
      else openMenu();
    }
    trackListener(trigger, 'click', onTriggerClick);

    // Requirement: Tap/click outside menu closes it
    // Approach: Document-level click handler checks if target is outside menu+trigger.
    function onDocumentClickForMenu(e) {
      if (menuOpen && !menu.contains(e.target) && !trigger.contains(e.target)) {
        closeMenu();
      }
    }
    trackListener(document, 'click', onDocumentClickForMenu);

    // Close on Escape key
    function onDocumentKeydown(e) {
      if (e.key === 'Escape' && isOpen()) {
        e.preventDefault();
        closeMenu();
      }
    }
    trackListener(document, 'keydown', onDocumentKeydown);

    // Requirement: keyboard navigation inside the open menu (BURGER_MENU.md):
    //   ArrowDown/ArrowUp move with wrap, Home/End jump, Tab is trapped so it
    //   cycles within the menu instead of escaping to the page behind it.
    // Approach: one keydown handler on the menu itself, walking the currently
    //   VISIBLE items — the inactive theme list is display:none'd and must not
    //   receive focus. offsetParent is null for hidden elements.
    // Note on the trap living here instead of a shared module: pwa.js has the
    //   same Tab-wrap for its install modal, but this file is a static classic
    //   script outside Vite's module graph and cannot import from src/ — the
    //   ~15 duplicated lines are the cost of that architecture.
    function visibleMenuItems() {
      var all = menu.querySelectorAll('a, button:not([disabled])');
      return Array.prototype.filter.call(all, function (el) {
        return el.offsetParent !== null;
      });
    }

    function onMenuKeydown(e) {
      if (!isOpen()) return;
      var items = visibleMenuItems();
      if (items.length === 0) return;
      var idx = items.indexOf(document.activeElement);

      if (e.key === 'ArrowDown') {
        e.preventDefault();
        items[(idx + 1) % items.length].focus();
      } else if (e.key === 'ArrowUp') {
        e.preventDefault();
        items[(idx - 1 + items.length) % items.length].focus();
      } else if (e.key === 'Home') {
        e.preventDefault();
        items[0].focus();
      } else if (e.key === 'End') {
        e.preventDefault();
        items[items.length - 1].focus();
      } else if (e.key === 'Tab') {
        // Focus trap: wrap at the boundaries instead of leaving the menu.
        if (e.shiftKey && (idx <= 0)) {
          e.preventDefault();
          items[items.length - 1].focus();
        } else if (!e.shiftKey && idx === items.length - 1) {
          e.preventDefault();
          items[0].focus();
        }
      }
    }
    trackListener(menu, 'keydown', onMenuKeydown);

    // Close menu when clicking [data-close] items (nav links, PDF button).
    // Theme toggle and theme picker do NOT have data-close — menu stays open.
    // The click event's default action (anchor navigation, button click) runs after
    // this handler returns, so closing synchronously here is safe — hiding the menu
    // via opacity/pointer-events doesn't cancel a pending fragment navigation, and
    // [data-close] buttons that trigger JS actions have already had their own
    // handlers fire via bubbling before this delegated one.
    function onMenuClick(e) {
      var item = e.target.closest('[data-close]');
      if (item) closeMenu();
    }
    trackListener(menu, 'click', onMenuClick);
  }

  // ===== Public dispose() =====
  // Pattern: TIMER_LEAKS.md variant 4. Releases every tracked listener and
  // restores body styles in case the menu was open. Idempotent.
  function dispose() {
    cleanups.forEach(function (fn) {
      try { fn(); } catch (e) { /* tolerate handler-removal errors */ }
    });
    cleanups.length = 0;
    if (typeof document !== 'undefined' && document.body) {
      document.body.style.overflow = '';
      document.body.style.scrollbarGutter = '';
    }
  }

  window.__theme = { dispose: dispose };
})();
